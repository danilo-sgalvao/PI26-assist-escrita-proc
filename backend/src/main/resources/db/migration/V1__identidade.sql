CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('ESTUDANTE', 'PROFESSOR')),
    menor BOOLEAN NOT NULL DEFAULT FALSE,
    consentimento_responsavel BOOLEAN NOT NULL DEFAULT FALSE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE aceite_termo (
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    versao VARCHAR(20) NOT NULL,
    aceito_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, versao)
);
